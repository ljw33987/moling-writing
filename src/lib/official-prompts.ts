interface TemplateInput {
  role: string
  task: string
  requirements: string[]
  output: string
}

function compose({ role, task, requirements, output }: TemplateInput): string {
  return [
    `【角色】${role}`,
    `【任务】${task}`,
    `【硬性要求】\n${requirements.map((r, i) => `${i + 1}. ${r}`).join('\n')}`,
    `【输出格式】${output}`,
    EXEC_RULES,
  ].join('\n\n')
}

