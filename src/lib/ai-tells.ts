/** 把模式目录渲染成给模型看的指令文本 */
export function renderAiTellCatalog(): string {
  const groups = new Map<string, AiTellPattern[]>()
  for (const p of AI_TELL_PATTERNS) {
    const list = groups.get(p.group)
    if (list) list.push(p)
    else groups.set(p.group, [p])
  }
  const lines: string[] = []
  for (const [group, patterns] of groups) {
    lines.push(`■ ${group}`)
    for (const p of patterns) {
      lines.push(`${p.id} ${p.name}｜识别：${p.signal}｜改法：${p.fix}${p.guard ? `｜不要误伤：${p.guard}` : ''}`)
    }
  }
  return lines.join('\n')
}
